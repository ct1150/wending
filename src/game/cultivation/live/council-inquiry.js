export function councilInquiry(state,menu){
 const e=state.events,record=e.council??'',h=hearings[record.length];
 const row=(title,lines,choices)=>({title,goal:'听清各方理由，再回到本议亲自决定',blocks:lines.filter(Boolean).map(text=>({kind:'narration',text})),choices});
 const back=menu('hear-council','带着听到的事，回到本议','council-book');
 const others=menu('other-voices','再听另一方，或查看实物','council-inquiry');
 if(e.node==='council-inquiry')return row('北山问事',[h.lead?.(record),'此处的询问发生在本次议事中。可以来回追问；在案边对照实物后，也可回到本议或暂缓离开。尚未落款，听过谁的话不算答应谁。',...h.people.map(p=>p[0])],[...h.people.map((p,i)=>menu('witness-'+i,p[0],'council-witness',{page:i})),menu('witness-2','到案边看实物，或暂缓离开','council-witness',{page:2})]);
 if(e.page===2)return row('案边的实物',[h.lead?.(record),h.trace],[others,back,menu('river-back','暂不落款，回去整备','hub')]);
 const p=h.people[e.page];
 return e.node==='council-question'?row(p[2],[p[3]],[others,back]):row(p[0],[h.lead?.(record),p[1]],[menu('ask-witness',p[2],'council-question'),others,back]);
}
