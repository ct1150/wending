function cleanText(raw, state) {
 let text = raw;
 for (const [exact, make] of SYSTEM_REWRITES) {
  if (text === exact) return make(state);
  if (text.includes(exact)) text = text.replace(exact, make(state));
 }
 for (const [pattern, replacement] of PHRASE_CLEANUPS) {
  text = text.replace(pattern, replacement);
 }
 text = text.replace(/\s{2,}/g, ' ').replace(/。。+/g, '。').trim();
 return text || raw;
}

export function polishV2Scene(scene, state) {
 if (!scene || state?.events?.version !== 2) return scene;
 const blocks = scene.blocks.map(block => ({
  ...block,
  text: cleanText(block.text, state),
 }));
 return { ...scene, blocks };
}
